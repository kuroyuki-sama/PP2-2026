#Programming 1. 우리는 리스트 함축과 내장 함수를 적절히 사용하면 많은 작업을 간단하게 수행할 수 있다. 예를 들어서 1부터 100사이 정수 중에서 3의 배수의 개수를 세어보자. 물론 이것은 for 반복 루프와 if 문을 사용하면 어렵지 않게 작성할 수 있다. 하지만 내장 함수와 리스트 함축을 이용하여 더 간단하게 작성해보자

three = [x for x in range(1, 100) if x % 3 == 0]
print(f"3의 배수의 개수 : {len(three)}")